    public TransaksiFrame(Transaksi transaksi) {
        initComponents();
        getContentPane().setBackground(new Color(67, 163, 154));
        setLocationRelativeTo(null);
        setTitle("SmartTrade-In - Struk Transaksi #" + transaksi.getIdTransaksi());

        lblNoTransaksi.setText("No. Transaksi : #" + transaksi.getIdTransaksi());
        lblPembeli.setText("Pembeli       : " + transaksi.getCustomer().getNama()
                + " (" + transaksi.getCustomer().getEmail() + ")");
        lblTanggal.setText("Tanggal       : " + transaksi.getTanggal().format(Format.TANGGAL));

        DefaultTableModel tabelModel = (DefaultTableModel) tblDetail.getModel();
        tabelModel.setRowCount(0);

        int nomor = 1;
        for (DetailTransaksi d : transaksi.getDaftarDetail()) {
            BarangElektronik b = d.getBarang();
            tabelModel.addRow(new Object[]{
                nomor++,
                b.getNama(),
                b.getMerek(),
                Format.jenis(b),
                String.valueOf(b.tentukanGrade()),
                Format.rupiah(d.getHarga())
            });
        }
        lblTotal.setText("Total Pembayaran: " + Format.rupiah(transaksi.getTotalHarga()));
    }

