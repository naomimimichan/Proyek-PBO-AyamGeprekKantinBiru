    private void muatData() {
        try {
            String nama = fieldCari.getText().trim();
            
            ArrayList<BarangElektronik> hasil = barangService.cariBarang(nama);

            hasil = barangService.cariBarang(nama);             

            barangService.urutkanByNama(hasil, cmbUrut.getSelectedIndex() == 0);
            isiTabel(hasil);

        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void isiTabel(ArrayList<BarangElektronik> hasil) {
        daftarTampil = hasil;
        tabelModel.setRowCount(0); 

        for (BarangElektronik b : hasil) {
            tabelModel.addRow(new Object[]{
                b.getId(),
                Format.jenis(b),
                b.getNama(),
                b.getMerek(),
                Format.spesifikasi(b),
                b.nilaiKondisi(),
                String.valueOf(b.tentukanGrade()),
                Format.rupiah(b.hitungHargaTradeIn())   
            });
        }
        perbaruiTotalDipilih();
    }

    private void perbaruiTotalDipilih() {
        int[] baris = tblBarang.getSelectedRows();

        if (baris.length == 0) {
            lblTotalDipilih.setText("Barang ditemukan: " + daftarTampil.size()
                    + "  |  Pilih barang di tabel (tahan Ctrl untuk memilih lebih dari satu)");
            return;
        }

        double total = 0;
        for (int r : baris) {
            total += daftarTampil.get(r).hitungHargaTradeIn();
        }
        lblTotalDipilih.setText("Dipilih: " + baris.length + " barang  |  Total: " + Format.rupiah(total));
    }
    
