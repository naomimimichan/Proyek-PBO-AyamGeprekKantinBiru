    private void btnBeliActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBeliActionPerformed
        // TODO add your handling code here:
        
        int[] baris = tblBarang.getSelectedRows();

        if (baris.length == 0) {
            JOptionPane.showMessageDialog(this, "Pilih minimal satu barang yang ingin dibeli!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        List<Integer> daftarId = new ArrayList<>();
        StringBuilder rincian = new StringBuilder();
        double total = 0;
        for (int r : baris) {
            BarangElektronik b = daftarTampil.get(r);
            daftarId.add(b.getId());
            rincian.append("- ").append(b.getNama()).append(" (")
                   .append(Format.rupiah(b.hitungHargaTradeIn())).append(")\n");
            total += b.hitungHargaTradeIn();
        }

        int pilih = JOptionPane.showConfirmDialog(this,
                "Beli " + baris.length + " barang berikut?\n\n" + rincian
                + "\nTotal: " + Format.rupiah(total),
                "Konfirmasi Pembelian", JOptionPane.YES_NO_OPTION);
        if (pilih != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            Transaksi transaksi = transaksiService.beli(customer, daftarId);

            JOptionPane.showMessageDialog(this, "Pembelian berhasil!\nNo. transaksi: #"
                    + transaksi.getIdTransaksi() + "\nTotal: " + Format.rupiah(transaksi.getTotalHarga()));

            new TransaksiFrame(transaksi).setVisible(true);

            muatData();

        } catch (StokTidakCukupException | BarangTidakDitemukanException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            muatData();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBeliActionPerformed

