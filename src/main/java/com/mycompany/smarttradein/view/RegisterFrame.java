    private void btnDaftarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDaftarActionPerformed
        // TODO add your handling code here:
        
        String nama = fieldNama.getText().trim();
        String email = fieldEmail.getText().trim();
        String password = new String(fieldPassword.getPassword());
        String konfirmasi = new String(fieldKonfirmasi.getPassword());

        if (nama.isEmpty() || email.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Semua kolom wajib diisi!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!email.matches("^[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+$")) {
            JOptionPane.showMessageDialog(this, "Format email tidak valid! Contoh: nama@mail.com",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            fieldEmail.requestFocus();
            return;
        }
        if (password.length() < 6) {
            JOptionPane.showMessageDialog(this, "Password minimal 6 karakter!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            fieldPassword.requestFocus();
            return;
        }
        if (!password.equals(konfirmasi)) {
            JOptionPane.showMessageDialog(this, "Password dan ulangi password tidak sama!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            fieldKonfirmasi.setText("");
            fieldKonfirmasi.requestFocus();
            return;
        }

        try {
            customerRepo.simpan(new Customer(nama, email, password));

            JOptionPane.showMessageDialog(this, "Registrasi berhasil! Silakan login.");
            new LoginFrame().setVisible(true);
            dispose();

        } catch (EmailSudahTerdaftarException ex) {

            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            fieldEmail.requestFocus();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDaftarActionPerformed

