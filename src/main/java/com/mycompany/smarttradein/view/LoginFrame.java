    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:
        
        String email = fieldEmail.getText().trim();
        String password = new String(fieldPassword.getPassword());

        if (email.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Email dan password wajib diisi!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Customer customer = customerRepo.login(email, password);

            if (customer == null) {
                JOptionPane.showMessageDialog(this, "Email atau password salah!",
                        "Login Gagal", JOptionPane.ERROR_MESSAGE);
                fieldPassword.setText("");
                fieldPassword.requestFocus();
                return;
            }

            JOptionPane.showMessageDialog(this, "Login berhasil! Selamat datang, " + customer.getNama());

            new MainFrame(customer).setVisible(true);
            dispose();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLoginActionPerformed

